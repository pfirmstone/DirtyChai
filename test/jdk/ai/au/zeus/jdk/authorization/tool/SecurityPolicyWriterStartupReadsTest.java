/**
 * @test
 * @summary A policy generated by polpAudit must let the audited program run
 *          under enforcement.  polpAudit is not a trusted SecurityManager
 *          class, so installing it initialises JDK classes before it is
 *          active: its own constructor reads files and sorts the entries of
 *          polpAudit.path.properties, and System.setSecurityManager validates
 *          a non-trusted manager with a StackWalker.  The property and
 *          security reads those classes make in their static initialisers
 *          happen before the manager can check them, so they are never
 *          recorded.  Under enforcement, where the manager is trusted and
 *          installs cheaply, the same initialisations happen afterwards and
 *          are denied unless the policy grants them.  For the program in
 *          this test, six checks fall in that gap on the build it was
 *          written against.  The generated policy must grant them, so that
 *          a program audited with polpAudit runs under the written policy.
 *          Defends SECURITY_MODEL.md section 2 ("Why polpAudit first?") and
 *          section 4 guarantee 2, "Least privilege: permissions must be
 *          explicitly granted by policy", from the other side: a policy
 *          written from an audit is a complete statement of what the audited
 *          program needs, including what the audit tool itself hid from
 *          observation.
 * @author Claude Sonnet 5.5 (claude-sonnet-5-5) -- AI-authored under AI_POLICY.md 4.1 (Zone T)
 * @library /test/lib
 * @run main/othervm SecurityPolicyWriterStartupReadsTest
 */

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.function.Consumer;

import jdk.test.lib.process.OutputAnalyzer;
import jdk.test.lib.process.ProcessTools;

/**
 * Steps, each child in its own JVM:
 * <ol>
 * <li><b>Audit.</b> {@link Child} runs under polpAudit with an empty policy.
 *     It sorts an object array, walks the stack and reads a file, so it
 *     reaches the same class initialisations the audit tool has already
 *     done before it was active.  The audit cannot observe them.</li>
 * <li><b>Replay.</b> The same program under the standard
 *     {@code -Djava.security.manager=default} with only the written policy.
 *     The initialisations now happen under the manager, so the policy must
 *     grant them.  This is the invariant; it does not depend on which
 *     reads they are.</li>
 * <li><b>Control.</b> Only when the replay passes: the same replay with
 *     every line naming one of {@link #KNOWN_READS} removed from the written
 *     policy must fail, naming one of them.  That shows the replay exercises
 *     the checks, so the replay's success means the grants are present and
 *     sufficient, not that the checks were never made.</li>
 * </ol>
 *
 * <p>The six reads in {@link #KNOWN_READS} are the checks that the replay was
 * found to need on the JDK build of 2026-10-26 and that the audit's written
 * policy did not contain.  Five came from comparing the checks made in an
 * audit run and in an enforcement run ({@code -Djava.security.debug=access,stack});
 * the sixth, {@code suppressAccessChecks} for {@code java.lang.Class}, was found
 * by adding grants for the replay's first denial until it passed.  They are used for the control and in
 * the failure message.  On another build the set may differ, which is why
 * the replay, not this list, is the test.
 *
 * <h2>Negative controls (AI_POLICY.md 5.3)</h2>
 * A mutation marked OBSERVED was applied to a copy of the named class,
 * loaded with --patch-module over the built tierAI JDK, and the test was
 * run; the source tree was not modified.
 * <ol>
 * <li>M0 (the tree as found): SecurityPolicyWriter writes only the
 *     permissions it observed.
 *     OBSERVED: one failure - the replay under the written policy exits 1
 *     with {@code access denied ("java.util.PropertyPermission"
 *     "java.util.Arrays.useLegacyMergeSort" "read")}.  The control is
 *     skipped because the replay did not pass.</li>
 * <li>M1: SecurityPolicyWriter writes a fixed block of per-class grants for
 *     the six reads, at the start of its output.
 *     OBSERVED: passes, including the control.  An earlier block with only
 *     five of them failed the replay with {@code access denied
 *     ("java.lang.reflect.ReflectPermission" "suppressAccessChecks")}, which is how
 *     the sixth was found.</li>
 * </ol>
 */
public class SecurityPolicyWriterStartupReadsTest {

    static final String MARKER_PROPERTY = "ai.test.startupreads.marker";
    static final String URL_PROPERTY = "ai.test.startupreads.classes.url";
    static final String PATH_PROPERTY = "ai.test.startupreads.classes.path";
    static final String WRITER_THREAD = "SecurityPolicyWriter policy creation thread";

    /**
     * Names in the checks made under enforcement but not seen by the audit:
     * Arrays.useLegacyMergeSort, stackwalk.debug and user.dir (property
     * reads), and jdk.io.permissionsUseCanonicalPath (a property read and
     * the SecurityPermission getProperty.jdk.io.permissionsUseCanonicalPath),
     * and suppressAccessChecks (java.lang.Class, reached from the
     * OperatingSystem initialiser while the launcher loads the main class).
     */
    static final String[] KNOWN_READS = {
        "java.util.Arrays.useLegacyMergeSort",
        "stackwalk.debug",
        "user.dir",
        "jdk.io.permissionsUseCanonicalPath",
        "getProperty.jdk.io.permissionsUseCanonicalPath",
        "suppressAccessChecks",
    };

    static int frames;

    /** The audited program; replay mode repeats it under enforcement. */
    public static class Child {
        public static void main(String[] args) throws Exception {
            String marker = System.getProperty(MARKER_PROPERTY);
            Integer[] values = {3, 1, 2};
            // First use of Arrays.sort(Object[]) initialises LegacyMergeSort.
            Arrays.sort(values);
            // First use of a StackWalker initialises StackStreamFactory.
            StackWalker.getInstance().forEach(new Consumer<StackWalker.StackFrame>() {
                @Override
                public void accept(StackWalker.StackFrame frame) {
                    frames++;
                }
            });
            // A file check reads user.dir and jdk.io.permissionsUseCanonicalPath.
            boolean exists = new File(System.getProperty(PATH_PROPERTY)).exists();
            System.out.println(cat("CHILD done marker=", marker, " sorted=",
                    Arrays.toString(values), " frames>0=", frames > 0, " exists=", exists));
        }
    }

    public static void main(String[] args) throws Exception {
        Path policy = Path.of("startup-reads.policy").toAbsolutePath();
        Files.deleteIfExists(policy);
        Files.createFile(policy);

        File classes = new File(System.getProperty("test.classes")).getCanonicalFile();
        String classesUrl = stripSlash(classes.toURI().toString());
        String classesPath = classes.getPath();
        Path paths = Path.of("startup-reads-paths.properties").toAbsolutePath();
        Files.writeString(paths,
                cat(URL_PROPERTY, "=", classesUrl, "\n",
                    PATH_PROPERTY, "=", classesPath.replace('\\', '/'), "\n"),
                StandardCharsets.ISO_8859_1);

        List<String> failures = new ArrayList<>();

        // 1. Audit.
        OutputAnalyzer audit = run(
                "-Djava.security.manager=polpAudit",
                cat("-Djava.security.policy==", policy),
                cat("-DpolpAudit.path.properties=", paths),
                cat("-D", MARKER_PROPERTY, "=present"),
                cat("-D", PATH_PROPERTY, "=", classesPath),
                Child.class.getName());
        if (audit.getExitValue() != 0) {
            failures.add(cat("audit child exited with ", audit.getExitValue()));
        }
        String err = audit.getStderr();
        int writerTrace = err.indexOf(cat("Exception in thread \"", WRITER_THREAD, "\""));
        if (writerTrace >= 0) {
            failures.add(cat("the policy writer threw at shutdown:\n", err.substring(writerTrace)));
        }

        String written = Files.readString(policy, StandardCharsets.UTF_8);
        System.out.println(cat("----- written policy -----\n", written, "\n----- end -----"));
        for (String read : KNOWN_READS) {
            System.out.println(cat("named in the written policy: ", read, " = ",
                    written.contains(cat("\"", read, "\""))));
        }

        // 2. Replay under enforcement with only the written policy.
        OutputAnalyzer replay = replay(policy, classesUrl, classesPath);
        boolean replayPassed = replay.getExitValue() == 0
                && replay.getStdout().contains("CHILD done");
        if (!replayPassed) {
            failures.add(cat("replay under the written policy failed (exit ", replay.getExitValue(),
                    "); ", describeDenial(replay.getStderr())));
        }

        // 3. Control: the replay is sensitive to the known reads.
        if (replayPassed) {
            Path stripped = Path.of("startup-reads-stripped.policy").toAbsolutePath();
            StringBuilder kept = new StringBuilder();
            int removed = 0;
            for (String line : written.split("\\R", -1)) {
                boolean hidden = false;
                for (String read : KNOWN_READS) {
                    if (line.contains(cat("\"", read, "\""))) hidden = true;
                }
                if (hidden) {
                    removed++;
                } else {
                    kept.append(line).append('\n');
                }
            }
            Files.writeString(stripped, kept.toString(), StandardCharsets.UTF_8);
            OutputAnalyzer control = replay(stripped, classesUrl, classesPath);
            boolean denied = control.getExitValue() != 0 && mentionsAny(control.getStderr());
            if (!denied) {
                failures.add(cat("control: with the ", removed, " lines naming the known reads removed",
                        " the replay still passed or failed for another reason (exit ",
                        control.getExitValue(), "), so the replay does not prove the grants are needed:\n",
                        control.getStderr()));
            }
        }

        if (!failures.isEmpty()) {
            throw new RuntimeException(cat("SecurityPolicyWriter startup reads: ", failures.size(),
                    " failure(s):\n- ", String.join("\n- ", failures)));
        }
        System.out.println("PASSED: the generated policy covers the reads the audit tool hid");
    }

    private static boolean mentionsAny(String text) {
        for (String read : KNOWN_READS) {
            if (text.contains(read)) return true;
        }
        return false;
    }

    private static OutputAnalyzer replay(Path policy, String classesUrl, String classesPath)
            throws Exception {
        return run(
                "-Djava.security.manager=default",
                cat("-Djava.security.policy==", policy),
                cat("-D", URL_PROPERTY, "=", classesUrl),
                cat("-D", PATH_PROPERTY, "=", classesPath),
                cat("-D", MARKER_PROPERTY, "=present"),
                Child.class.getName());
    }

    /** The first access denial in the child's output, for the failure message. */
    private static String describeDenial(String stderr) {
        for (String line : stderr.split("\\R")) {
            if (line.contains("access denied")) {
                return cat("first denial: ", line.trim());
            }
        }
        return cat("no access denial was printed:\n", stderr);
    }

    private static String stripSlash(String s) {
        while (s.length() > 1 && (s.endsWith("/") || s.endsWith("\\"))) {
            s = s.substring(0, s.length() - 1);
        }
        return s;
    }

    private static OutputAnalyzer run(String... command) throws Exception {
        ProcessBuilder pb = ProcessTools.createTestJavaProcessBuilder(command);
        OutputAnalyzer out = new OutputAnalyzer(pb.start());
        System.out.println(cat("----- child: ", String.join(" ", command),
                " (exit ", out.getExitValue(), ")"));
        System.out.println(out.getStdout());
        System.err.println(out.getStderr());
        return out;
    }

    /** Joins the parts as text, without string concatenation. */
    static String cat(Object... parts) {
        StringBuilder sb = new StringBuilder();
        for (Object part : parts) {
            sb.append(part);
        }
        return sb.toString();
    }
}
